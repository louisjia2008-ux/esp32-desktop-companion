#pragma once

#include <Arduino.h>

namespace uifont {

// One pre-rendered glyph. (x, y) is the top-left of the bitmap relative to
// the pen position on the baseline; data starts at `offset` bytes into the
// font's table, row-major, `bytesPerPixel` per pixel.
struct GlassGlyph {
  uint16_t codepoint;
  int8_t x;
  int8_t y;
  uint8_t width;
  uint8_t height;
  uint8_t advance;
  uint32_t offset;
};

struct GlassFont {
  const GlassGlyph* glyphs;
  uint8_t count;
  const uint8_t* data;
  // 3: clock cells, column-major (coverage, light, dx<<4|dy); 1: coverage, row-major
  uint8_t bytesPerPixel;
  uint8_t height;         // nominal glyph height in pixels
};

// Generated by tools/gen_glass_font.py into glass_font_data.cpp.
extern const GlassFont kClockFont;   // digits and ':' for the glass time
extern const GlassFont kMediumFont;  // digits and '%' for usage gauges
extern const GlassFont kDateFont;    // digits and the date's CJK characters

const GlassGlyph* findGlyph(const GlassFont& font, uint32_t codepoint);

}  // namespace uifont
